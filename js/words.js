export const WORDS = RAW.map(([w, pinyin, hsk, en, pl]) => ({ w, pinyin, hsk, en, pl }));
export const BY_WORD = new Map(WORDS.map((x) => [x.w, x]));

// Słowa zawierające dany znak (kolejność listy: niższy poziom i częstsze najpierw).
const BY_CHAR = new Map();
for (const x of WORDS) for (const ch of new Set(x.w)) (BY_CHAR.get(ch) || BY_CHAR.set(ch, []).get(ch)).push(x);
export const wordsWith = (hanzi) => BY_CHAR.get(hanzi) || [];

const tokens = (s) => s.split(/[;,]/).map((t) => norm(t).trim()).filter(Boolean);
const INDEX = WORDS.map((x) => ({ x, py: norm(x.pinyin).replace(/\s+/g, '').replace(/v/g, 'u'), en: tokens(x.en), pl: tokens(x.pl) }));

function scoreMeaning(list, q) {
  let best = 0;
  for (const t of list) {
    if (t === q) best = Math.max(best, 80);
    else if (q.length < 3) continue;
    else if (t.startsWith(q)) best = Math.max(best, 60);
    else if (t.split(/\s+/).some((w) => w.startsWith(q))) best = Math.max(best, 50);
    else if (t.includes(q)) best = Math.max(best, 30);
  }
  return best;
}

// Szukanie słów: po znakach, pinyin bez tonów (całe słowo, np. „kafei”) i po znaczeniach PL/EN.
export function searchWords(raw, limit = 30) {
  const text = raw.trim();
  if (!text) return [];
  const q = norm(text).replace(/[0-9]/g, '').trim();
  const qp = q.replace(/\s+/g, '').replace(/v/g, 'u');
  const hasHan = /[\u4e00-\u9fff]/.test(text);
  const out = [];
  for (const row of INDEX) {
    let s = 0;
    if (hasHan) {
      if (row.x.w === text) s = 100;
      else if (row.x.w.includes(text)) s = 80;
      else if ([...text].some((ch) => row.x.w.includes(ch)) && [...text].length > 1 && text.includes(row.x.w)) s = 60;
    } else if (qp) {
      if (row.py === qp) s = 90;
      else if (row.py.startsWith(qp)) s = 70;
      else if (qp.length >= 3 && row.py.includes(qp)) s = 40;
      if (q) s = Math.max(s, scoreMeaning(row.pl, q), scoreMeaning(row.en, q));
    }
    if (s) out.push({ x: row.x, s });
  }
  return out.sort((a, b) => b.s - a.s || a.x.hsk - b.x.hsk).slice(0, limit).map((r) => r.x);
}
